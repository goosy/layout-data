import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test, { after, describe } from "node:test";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { render_types, yaml, yaml_file } from "./target.js";
import { fresh_scope } from "./share.js";

/** The syntax errors of a text taken as TypeScript (a declaration file is parsed as the same syntax). */
function syntax_errors(text) {
	const { diagnostics } = ts.transpileModule(text, { reportDiagnostics: true, fileName: "layout_types.ts" });
	return (diagnostics ?? []).map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
}

const ITEMS = [
	{ name: "id", type: "UInt", offset: 0, init_value: 1, comment: "Identifier" },
	{ name: "pressure", type: "Real", offset: 16, init_value: 0 },
	{ name: "run", type: "Bool", offset: 48, init_value: false },
	{ name: "pad", type: "Byte", offset: 56, init_value: 0 },
];

let scope_count = 0;

/** A scope name of its own: render_types creates a scope, and a name is used once in the process. */
function scope_name() {
	return `Ty_Scope_${scope_count++}`;
}

/** A description object of the entries, [name, items] each. */
function description_of(entries) {
	return { layouts: entries.map(([name]) => name), item_tables: Object.fromEntries(entries) };
}

/** The text of the layouts of the entries, in a scope of its own. */
function render_of(entries, options = {}) {
	return render_types(description_of(entries), { scope: scope_name(), ...options });
}

describe("8 render_types of layout-data/dev", () => {
	test("one interface of tags and one data block type per layout, from the tags in layout order", () => {
		const scope = scope_name();
		const text = render_types(description_of([["Ty_Basic", ITEMS]]), { scope, source: "pump.yaml" });
		assert.equal(text, `// Generated from pump.yaml. Do not edit.
import type { Ldata } from "layout-data";
//
// In JavaScript, a JSDoc cast names the type of the value:
//   const data = /** @type {import("<this file>").Ty_Basic_Ldata} */ (get_scope("${scope}").get_layout("Ty_Basic").create_ldata("data_1"));

/** Tags of the Ty_Basic data block. */
export interface Ty_Basic_Tags {
\t/** Identifier */
\tid: number;
\tpressure: number;
\trun: boolean;
\tpad: number;
}

/** A Ty_Basic data block, with its tags as properties. */
export type Ty_Basic_Ldata = Ldata & Ty_Basic_Tags;
`);
		assert.deepEqual(syntax_errors(text), []);
	});

	test("description objects without source: the header names no file, and Ldata comes from layout-data", () => {
		const text = render_of([["Ty_Default", ITEMS]]);
		assert.ok(text.startsWith("// Generated by render_types. Do not edit.\nimport type { Ldata } from \"layout-data\";\n"), text);
		assert.deepEqual(syntax_errors(text), []);
	});

	test("the scope is app by default, and only names the scope in the example of the header", () => {
		// the only call of this process with the default scope name
		const text = render_types(description_of([["Ty_App", ITEMS]]));
		assert.ok(text.includes("get_scope(\"app\").get_layout(\"Ty_App\")"), text);
	});

	test("the files read by yaml_file are named in the header, and descriptions of any origin are taken", () => {
		const dir = mkdtempSync(join(tmpdir(), "render-types-"));
		try {
			const a = join(dir, "a.yaml");
			const b = join(dir, "b.yaml");
			writeFileSync(a, "layouts: [Ty_File_A]\nitem_tables:\n  Ty_File_A:\n    - { name: x, type: UInt, offset: 0 }\n");
			writeFileSync(b, "layouts: [Ty_File_B]\nitem_tables:\n  Ty_File_B:\n    - { name: y, type: UInt, offset: 0 }\n");
			const one = render_types(yaml_file(a), { scope: scope_name() });
			assert.ok(one.startsWith(`// Generated from ${a}. Do not edit.\n`), one);
			const both = render_types([yaml_file(a), yaml_file(b)], { scope: scope_name() });
			assert.ok(both.startsWith(`// Generated from ${a}, ${b}. Do not edit.\n`), both);
			assert.ok(both.includes("export interface Ty_File_A_Tags {") && both.includes("export interface Ty_File_B_Tags {"), both);
			const mixed = render_types([yaml_file(a), description_of([["Ty_Mixed_Object", ITEMS]])], { scope: scope_name() });
			assert.ok(mixed.startsWith("// Generated by render_types. Do not edit.\n"), mixed);
			assert.ok(mixed.includes("export interface Ty_Mixed_Object_Tags {"), mixed);
			const text = render_types(yaml("layouts: [Ty_Text]\nitem_tables:\n  Ty_Text:\n    - { name: z, type: UInt, offset: 0 }\n"), { scope: scope_name() });
			assert.ok(text.startsWith("// Generated by render_types. Do not edit.\n"), text);
			const named = render_types(yaml_file(a), { scope: scope_name(), source: "a layout" });
			assert.ok(named.startsWith("// Generated from a layout. Do not edit.\n"), named);
		} finally {
			rmSync(dir, { recursive: true, force: true });
		}
	});

	test("Ldata is always imported from layout-data: no option sets the module", () => {
		const text = render_of([["Ty_Module", ITEMS]], { ldata_module: "../src/index.js" });
		assert.ok(text.includes("import type { Ldata } from \"layout-data\";"), text);
		assert.ok(!text.includes("../src/index.js"), text);
	});

	test("invalid descriptions and scope names throw as register_layout and create_scope do", () => {
		assert.throws(() => render_of([["Ty_Invalid", [{ name: "a", type: "Nope", offset: 0 }]]]), (error) => Array.isArray(error.errors) && error.errors.length > 0);
		assert.throws(() => render_types({ layouts: [] }, { scope: scope_name() }), Error);
		assert.throws(() => render_types(description_of([["Ty_Bad_Scope", ITEMS]]), { scope: "not-an-identifier" }), /not an identifier/);
		assert.throws(() => render_types(description_of([["Ty_Bad_Scope", ITEMS]]), { scope: 1 }), TypeError);
	});

	test("a scope has no render_types: rendering the types is in the development entry", () => {
		assert.equal("render_types" in fresh_scope(), false);
	});

	test("the layout name is used as it is: no case is folded, so different names never collide", () => {
		const text = render_of([["ty_a_b", ITEMS], ["TY_A_B", ITEMS], ["Ty_Mixed", ITEMS]]);
		for (const name of ["ty_a_b", "TY_A_B", "Ty_Mixed"]) {
			assert.ok(text.includes(`export interface ${name}_Tags {`), name);
			assert.ok(text.includes(`export type ${name}_Ldata = Ldata & ${name}_Tags;`), name);
		}
		const interfaces = text.match(/export interface \w+/g);
		assert.equal(new Set(interfaces).size, interfaces.length);
		assert.deepEqual(syntax_errors(text), []);
	});

	test("a */ in a comment is escaped, and a comment of several lines stays inside its comment", () => {
		const text = render_of([["Ty_Comment", [
			{ name: "a", type: "UInt", offset: 0, init_value: 0, comment: "ends */ here" },
			{ name: "b", type: "UInt", offset: 16, init_value: 0, comment: "first line\nsecond line */ x" },
		]]]);
		assert.ok(text.includes("/** ends *\\/ here */"), text);
		assert.ok(text.includes("\t/**\n\t * first line\n\t * second line *\\/ x\n\t */"), text);
		assert.deepEqual(syntax_errors(text), []);
		assert.equal(text.match(/\bb: number;/).length, 1);
	});

	test("the case style of a layout name is the caller's: every style is kept as it is", () => {
		const text = render_of([["ty_snake", ITEMS], ["Ty_Snake_Pascal", ITEMS], ["TyPascal", ITEMS], ["TY_UPPER", ITEMS]]);
		for (const name of ["ty_snake", "Ty_Snake_Pascal", "TyPascal", "TY_UPPER"]) {
			assert.ok(text.includes(`export interface ${name}_Tags {`), name);
		}
		assert.deepEqual(syntax_errors(text), []);
	});

	test("a layout name in any script is kept as it is, since it is an identifier", () => {
		const text = render_of([["TY_水泵", ITEMS]]);
		assert.ok(text.includes("export interface TY_水泵_Tags {"), text);
		assert.ok(text.includes("export type TY_水泵_Ldata = Ldata & TY_水泵_Tags;"), text);
		assert.deepEqual(syntax_errors(text), []);
	});

	test("the Bool tags are boolean, and every other type is number", () => {
		const types = ["Byte", "SInt", "USInt", "Int", "UInt", "Word", "DInt", "UDInt", "DWord", "Real"];
		const items = types.map((type) => ({ name: `t_${type}`, type, offset: 0, init_value: 0 }));
		items.forEach((item, index) => { item.offset = index * 32; });
		items.push({ name: "flag", type: "Bool", offset: 32 * types.length, init_value: false });
		items.push({ name: "pad", type: "Byte", offset: 32 * types.length + 8, init_value: 0 });
		const text = render_of([["Ty_Types", items]]);
		for (const type of types) assert.ok(text.includes(`\tt_${type}: number;`), type);
		assert.ok(text.includes("\tflag: boolean;"));
	});
});

describe("8.1 the command line layout-types", { skip: typeof import.meta.main !== "boolean" && "needs Node.js >= 24.2 (import.meta.main)" }, () => {
	// the bundle the bin of package.json points to, as installed for the user (built by pnpm test)
	const package_url = new URL("../../package.json", import.meta.url);
	const dev_file = fileURLToPath(new URL(JSON.parse(readFileSync(package_url, "utf8")).bin["layout-types"], package_url));
	const dir = mkdtempSync(join(tmpdir(), "layout-types-"));
	after(() => rmSync(dir, { recursive: true, force: true }));

	const pump_file = join(dir, "pump.yaml");
	writeFileSync(pump_file, "layouts: [Pump]\nitem_tables:\n  Pump:\n    - { name: pressure, type: Real, offset: 0, init_value: 0, comment: Outlet pressure }\n    - { name: run, type: Bool, offset: 32 }\n    - { name: pad, type: Byte, offset: 40 }\n    - { name: id, type: UInt, offset: 48 }\n");
	const bad_file = join(dir, "bad.yaml");
	writeFileSync(bad_file, "layouts: [Bad]\nitem_tables:\n  Bad:\n    - { name: a, type: Nope, offset: 0 }\n    - { name: b, type: UInt, offset: 3 }\n");
	writeFileSync(join(dir, "unclosed.yaml"), "layouts: [unclosed\n");

	/** Runs the command line as a user does, with the running Node.js. */
	function run(...args) {
		return spawnSync(process.execPath, [dev_file, ...args], { encoding: "utf8" });
	}

	test("the text of the layouts of the description files goes to the standard output", () => {
		const { status, stdout, stderr } = run(pump_file);
		assert.equal(status, 0, stderr);
		assert.ok(stdout.startsWith(`// Generated from ${pump_file}. Do not edit.\nimport type { Ldata } from "layout-data";\n`), stdout);
		assert.ok(stdout.includes("get_scope(\"app\")"), stdout);
		assert.ok(stdout.includes("export type Pump_Ldata = Ldata & Pump_Tags;"), stdout);
		assert.ok(stdout.includes("\t/** Outlet pressure */\n\tpressure: number;"), stdout);
		assert.deepEqual(syntax_errors(stdout), []);
	});

	test("--scope names the scope of the header, and -o / --out write a file", () => {
		for (const flag of ["-o", "--out"]) {
			const out_file = join(dir, `types${flag}.d.ts`);
			const { status, stdout, stderr } = run(pump_file, "--scope", "plant", flag, out_file);
			assert.equal(status, 0, stderr);
			assert.equal(stdout, "");
			const text = readFileSync(out_file, "utf8");
			assert.ok(text.includes("get_scope(\"plant\")"), text);
			assert.ok(text.includes("export interface Pump_Tags {"), text);
		}
	});

	test("--help shows the usage with the version requirement", () => {
		for (const flag of ["-h", "--help"]) {
			const { status, stdout } = run(flag);
			assert.equal(status, 0);
			assert.ok(stdout.startsWith("Usage: layout-types "), stdout);
			assert.ok(stdout.includes("Node.js >= 24.2"), stdout);
		}
	});

	test("wrong arguments: the reason and the usage go to the standard error, with a non-zero code", () => {
		for (const args of [[], ["--nope", pump_file], [pump_file, "--scope"]]) {
			const { status, stdout, stderr } = run(...args);
			assert.equal(status, 1, args.join(" "));
			assert.equal(stdout, "");
			assert.ok(stderr.startsWith("layout-types: "), stderr);
			assert.ok(stderr.includes("Usage: layout-types "), stderr);
		}
	});

	test("invalid descriptions or scope name: every error goes to the standard error, and no file is written", () => {
		const out_file = join(dir, "never.d.ts");
		const bad = run(bad_file, "-o", out_file);
		assert.equal(bad.status, 1);
		assert.ok(bad.stderr.startsWith("layout-types: "), bad.stderr);
		assert.ok(bad.stderr.split("\n").filter((line) => line.startsWith("  ")).length >= 2, bad.stderr);
		const missing = run(join(dir, "missing.yaml"), pump_file, join(dir, "unclosed.yaml"), "-o", out_file);
		assert.equal(missing.status, 1);
		assert.ok(missing.stderr.startsWith("layout-types: invalid description files\n"), missing.stderr);
		assert.ok(missing.stderr.includes("missing.yaml") && missing.stderr.includes("unclosed.yaml"), missing.stderr);
		const bad_scope = run(pump_file, "--scope", "not-an-identifier", "-o", out_file);
		assert.equal(bad_scope.status, 1);
		assert.ok(bad_scope.stderr.includes("not an identifier"), bad_scope.stderr);
		assert.equal(existsSync(out_file), false);
	});

	test("imported, the module runs no command line", async () => {
		const { dev } = await import("./target.js");
		assert.deepEqual(Object.keys(dev), ["render_types"]);
	});
});
