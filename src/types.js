// Renders TypeScript declarations of compiled layouts, for editor completion
// of the tag accessors (doc/spec-layout.md §5, doc/design.md §4).

/**
 * Renders a text as a doc comment, one line or several, with the `*` and `/`
 * pair that would end the comment early escaped.
 *
 * @param {string} text
 * @param {string} indent
 * @returns {string[]}
 */
function doc_comment(text, indent) {
	const lines = String(text).replaceAll("*/", "*\\/").split(/\r?\n/);
	if (lines.length === 1) return [`${indent}/** ${lines[0]} */`];
	return [`${indent}/**`, ...lines.map((line) => `${indent} * ${line}`.trimEnd()), `${indent} */`];
}

/**
 * Renders a declaration file with, for each layout, an interface of
 * its tags (`<Layout>_Tags`, one property per tag) and the type of its data
 * block (`<Layout>_Ldata`). The layout name is used as it is, with the case
 * it has; a layout name is an identifier, so it is always part of a valid
 * type name. `Ldata` is always imported from "layout-data", the name of the
 * package: where the caller gets it from is the caller's matter. Internal:
 * render_types of dev.js calls it.
 *
 * In JavaScript a JSDoc cast names the type of the value, which an editor
 * uses for completion and, with `checkJs`, to check the tags:
 *
 * ```js
 * const pump = /** @type {import("./layout_types.js").Pump_Ldata} *\/ (get_scope("app").get_layout("Pump").create_ldata("pump_1"));
 * ```
 *
 * @param {string} scope_name - The name of the scope, for the example in the header.
 * @param {import("./typedefs.js").Layout_Desc[]} layouts - The layouts, their names distinct.
 * @param {object} [options]
 * @param {string} [options.source] - The layout file, named in the header; the header names none when it is omitted.
 * @returns {string}
 */
export function render_declarations(scope_name, layouts, { source } = {}) {
	const names = layouts.map((layout) => layout.name);
	const lines = [
		source === undefined ? "// Generated by render_types. Do not edit." : `// Generated from ${source}. Do not edit.`,
		"import type { Ldata } from \"layout-data\";",
	];
	if (names.length > 0) {
		lines.push(
			"//",
			"// In JavaScript, a JSDoc cast names the type of the value:",
			`//   const data = /** @type {import("<this file>").${names[0]}_Ldata} */ (get_scope("${scope_name}").get_layout("${names[0]}").create_ldata("data_1"));`,
		);
	}
	for (const layout of layouts) {
		const { name } = layout;
		lines.push("", `/** Tags of the ${name} data block. */`, `export interface ${name}_Tags {`);
		for (const item of layout.items) {
			if (item.comment) lines.push(...doc_comment(item.comment, "\t"));
			const ts_type = item.type.toLowerCase() === "bool" ? "boolean" : "number";
			lines.push(`\t${item.name}: ${ts_type};`);
		}
		lines.push("}", "", `/** A ${name} data block, with its tags as properties. */`, `export type ${name}_Ldata = Ldata & ${name}_Tags;`);
	}
	return `${lines.join("\n")}\n`;
}
